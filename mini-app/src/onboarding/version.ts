// mini-app/src/onboarding/version.ts
// Версия онбординга.
//
// Поднимайте значение при каждом изменении набора слайдов ИЛИ правовых
// текстов: все пользователи увидят новый онбординг по одному разу
// (сравнение с версией, сохранённой на бэкенде в User.onboardingVersion).
//
// "2" — слайды + обязательный акцепт Пользовательского соглашения и
// Политики конфиденциальности (редакция от 8 сентября 2026 года) на
// блокирующем экране ConsentGate. Версия сохраняется ТОЛЬКО кнопкой
// «Принять» — просмотр/пропуск слайдов согласием не считается.
//
// Константа вынесена из slides.ts намеренно: slides.ts загружается лениво
// (dynamic import), а статический импорт версии не должен тянуть
// base64-изображения в начальный бандл.
export const ONBOARDING_VERSION = "2";

/**
 * Нужно ли показывать онбординг: показываем, если пользователь ещё не видел
 * текущую версию слайдов (null/undefined — онбординг не проходил).
 */
export function shouldShowOnboarding(
  completedVersion: string | null | undefined,
): boolean {
  return completedVersion !== ONBOARDING_VERSION;
}
